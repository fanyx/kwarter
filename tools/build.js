"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const ENTRY = "src/index.js";
const OUTPUT = path.join(ROOT, "contents", "code", "main.js");
const HEADER = "// Generated by tools/build.js. Do not edit by hand.\n";

const REQUIRE_RE = /\brequire\(\s*(['"])([^'"]+)\1\s*\)/g;

function resolveRelative(fromId, spec) {
    if (!spec.startsWith(".")) {
        throw new Error(`kwarter build: only relative requires are supported (${fromId} -> ${spec})`);
    }
    const base = path.posix.dirname(fromId);
    let id = path.posix.normalize(path.posix.join(base, spec));
    if (!id.endsWith(".js")) {
        id += ".js";
    }
    return id;
}

function dependenciesOf(id) {
    const source = fs.readFileSync(path.join(ROOT, id), "utf8");
    const deps = [];
    let match;
    REQUIRE_RE.lastIndex = 0;
    while ((match = REQUIRE_RE.exec(source))) {
        deps.push(resolveRelative(id, match[2]));
    }
    return deps;
}

function collect(id, seen, order) {
    if (seen.has(id)) {
        return;
    }
    seen.add(id);
    for (const dep of dependenciesOf(id)) {
        if (!fs.existsSync(path.join(ROOT, dep))) {
            throw new Error(`kwarter build: cannot resolve ${dep} from ${id}`);
        }
        collect(dep, seen, order);
    }
    order.push(id);
}

function indent(text, spaces) {
    const pad = " ".repeat(spaces);
    return text
        .split("\n")
        .map((line) => (line.length > 0 ? pad + line : line))
        .join("\n");
}

function rewriteRequires(id, source) {
    return source.replace(REQUIRE_RE, (match, quote, spec) => {
        return `require(${JSON.stringify(resolveRelative(id, spec))})`;
    });
}

function renderModules(order) {
    const parts = [];
    for (const id of order) {
        const source = rewriteRequires(
            id,
            fs.readFileSync(path.join(ROOT, id), "utf8").replace(/\s+$/, "")
        );
        parts.push(
            `        ${JSON.stringify(id)}: function (module, exports, require) {\n` +
            `${indent(source, 12)}\n` +
            "        },"
        );
    }
    return parts.join("\n");
}

function bundle() {
    const order = [];
    collect(ENTRY, new Set(), order);

    return (
        HEADER +
        "(function () {\n" +
        '    "use strict";\n' +
        "\n" +
        "    var modules = {\n" +
        renderModules(order) +
        "\n" +
        "    };\n" +
        "\n" +
        "    var cache = {};\n" +
        "\n" +
        "    function load(id) {\n" +
        "        if (cache[id]) {\n" +
        "            return cache[id].exports;\n" +
        "        }\n" +
        "        var factory = modules[id];\n" +
        "        if (!factory) {\n" +
        '            throw new Error("kwarter: module not found: " + id);\n' +
        "        }\n" +
        "        var module = { exports: {} };\n" +
        "        cache[id] = module;\n" +
        "        factory(module, module.exports, load);\n" +
        "        return module.exports;\n" +
        "    }\n" +
        "\n" +
        '    if (typeof module !== "undefined" && module.exports) {\n' +
        "        var layout = load(\"src/core/layout.js\");\n" +
        "        var windows = load(\"src/core/windows.js\");\n" +
        "        var state = load(\"src/core/state.js\");\n" +
        "        var bootstrap = load(\"src/bootstrap.js\");\n" +
        "        module.exports = {\n" +
        "            GAP: layout.GAP,\n" +
        "            MAX_WINDOWS: layout.MAX_WINDOWS,\n" +
        "            slotRects: layout.slotRects,\n" +
        "            directionalTarget: layout.directionalTarget,\n" +
        "            chooseVictimIndex: layout.chooseVictimIndex,\n" +
        "            chooseVictim: state.chooseVictim,\n" +
        "            swapSlots: layout.swapSlots,\n" +
        "            fitToMinSize: layout.fitToMinSize,\n" +
        "            rectsClose: layout.rectsClose,\n" +
        "            eligible: windows.eligible,\n" +
        "            stateKey: windows.stateKey,\n" +
        "            resolveRoot: windows.resolveRoot,\n" +
        "            main: bootstrap.main,\n" +
        "        };\n" +
        "    } else {\n" +
        '        load("src/index.js");\n' +
        "    }\n" +
        "}());\n"
    );
}

function writeBundle() {
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, bundle());
}

if (require.main === module) {
    writeBundle();
}

module.exports = {
    bundle,
};
