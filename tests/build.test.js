const test = require("node:test");
const assert = require("node:assert/strict");
const vm = require("node:vm");

const { bundle } = require("../tools/build.js");

test("bundle builds and parses as a KWin script", () => {
    const source = bundle();

    assert.equal(source.startsWith("// Generated by tools/build.js."), true);
    assert.equal(/Qt\./.test(source), false);
    assert.equal(/callLater/.test(source), false);
    assert.equal(/new QTimer\(\)/.test(source), true);

    new vm.Script(source, { filename: "contents/code/main.js" });
});
